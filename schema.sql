create table if not exists public.site_links (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  kind text not null check (kind in ('player', 'agent')),
  url text not null,
  description text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.site_links enable row level security;

-- Public can read only enabled links.
drop policy if exists "Public can read enabled links" on public.site_links;
create policy "Public can read enabled links"
on public.site_links for select
to anon, authenticated
using (enabled = true);

-- Only the designated admin UUID can read all rows, including hidden links.
